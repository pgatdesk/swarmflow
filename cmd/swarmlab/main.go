// Command swarmlab runs SwarmFlow experiments.
//
//	swarmlab sim   [-scenario NAME|all] [-trials N] [-json FILE] [-md FILE]
//	swarmlab netem -scenario FILE.json [-trials N] [-out DIR] [-bin DIR] [-work DIR] [-only V1,V2]
//
// "sim" runs the discrete-event simulator (internal/sim): the real scheduling
// and peer-estimation code on a modelled network. Results are simulated.
//
// "netem" runs real swarmflow processes, each in its own Linux network
// namespace with its access link shaped by tc netem (decision 0005). It needs
// Linux (WSL2) and root.
package main

import (
	"context"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"os"
	"os/signal"
	"path/filepath"
	"runtime"
	"strings"
	"sync"
	"syscall"
	"time"

	"github.com/pgatdesk/swarmflow/internal/lab"
	"github.com/pgatdesk/swarmflow/internal/sim"
)

const usage = `usage:
  swarmlab sim   [-scenario NAME|all] [-trials N] [-json FILE] [-md FILE]
  swarmlab netem -scenario FILE.json [-trials N] [-out DIR] [-bin DIR] [-work DIR] [-only V1,V2]`

func main() {
	if len(os.Args) < 2 {
		fmt.Fprintln(os.Stderr, usage)
		os.Exit(2)
	}
	var err error
	switch os.Args[1] {
	case "sim":
		err = cmdSim(os.Args[2:])
	case "netem":
		err = cmdNetem(os.Args[2:])
	default:
		fmt.Fprintln(os.Stderr, usage)
		os.Exit(2)
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, "error:", err)
		os.Exit(1)
	}
}

func cmdNetem(args []string) error {
	fs := flag.NewFlagSet("netem", flag.ExitOnError)
	scenarioPath := fs.String("scenario", "", "scenario JSON file (required)")
	trials := fs.Int("trials", 5, "trials per variant")
	exe, _ := os.Executable()
	bin := fs.String("bin", filepath.Dir(exe), "directory with the Linux swarmflow and tracker binaries")
	work := fs.String("work", "/tmp/sf-lab", "scratch directory on a local Linux file system")
	out := fs.String("out", "docs/results", "directory for <scenario>.json and <scenario>.md")
	only := fs.String("only", "", "comma-separated variant names to run (default: all)")
	fs.Parse(args)
	if *scenarioPath == "" {
		return errors.New("-scenario is required")
	}
	if err := lab.Supported(); err != nil {
		return err
	}
	sc, err := lab.LoadScenario(*scenarioPath)
	if err != nil {
		return err
	}
	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
	defer stop()
	opt := lab.Options{BinDir: *bin, Work: *work, Trials: *trials, Log: os.Stderr}
	if *only != "" {
		opt.Only = strings.Split(*only, ",")
	}
	start := time.Now()
	res, err := lab.RunScenario(ctx, sc, opt)
	if res == nil {
		return err
	}
	md := fmt.Sprintf("## Network experiment: %s\n\nGenerated by `swarmlab netem -scenario %s -trials %d` on %s "+
		"(%s, %d CPUs), %s total. Measured with real processes and kernel traffic shaping on one host.\n\n%s",
		sc.Name, filepath.ToSlash(*scenarioPath), *trials, time.Now().Format("2006-01-02"), runtime.Version(),
		runtime.NumCPU(), time.Since(start).Round(time.Second), res.Markdown())
	fmt.Print(md)
	b, jerr := json.MarshalIndent(res, "", "  ")
	if jerr != nil {
		return jerr
	}
	if werr := writeFile(filepath.Join(*out, sc.Name+".json"), b); werr != nil {
		return werr
	}
	if werr := writeFile(filepath.Join(*out, sc.Name+".md"), []byte(md)); werr != nil {
		return werr
	}
	return err
}

func cmdSim(args []string) error {
	fs := flag.NewFlagSet("sim", flag.ExitOnError)
	name := fs.String("scenario", "all", "scenario name or all")
	trials := fs.Int("trials", 20, "trials per variant")
	jsonOut := fs.String("json", "", "write full results as JSON")
	mdOut := fs.String("md", "", "write the result tables as Markdown")
	fs.Parse(args)

	var scs []sim.Scenario
	var names []string
	for _, sc := range sim.Scenarios() {
		names = append(names, sc.Name)
		if *name == "all" || *name == sc.Name {
			scs = append(scs, sc)
		}
	}
	if len(scs) == 0 {
		return fmt.Errorf("unknown scenario %q (have: %s)", *name, strings.Join(names, ", "))
	}
	if *trials < 1 {
		return errors.New("-trials must be ≥ 1")
	}

	start := time.Now()
	results := make([]sim.ScenarioResult, len(scs))
	var wg sync.WaitGroup
	sem := make(chan struct{}, runtime.NumCPU())
	for i, sc := range scs {
		wg.Go(func() {
			sem <- struct{}{}
			defer func() { <-sem }()
			results[i] = sim.RunScenario(sc, *trials)
		})
	}
	wg.Wait()

	var md strings.Builder
	fmt.Fprintf(&md, "## Simulated scheduler comparison\n\nGenerated by `swarmlab sim -trials %d` (%s, %s). "+
		"These are **simulation** results from the model described in internal/sim, not network measurements.\n\n",
		*trials, time.Now().Format("2006-01-02"), runtime.Version())
	for _, r := range results {
		md.WriteString(r.Markdown())
		md.WriteString("\n")
	}
	fmt.Print(md.String())
	fmt.Fprintf(os.Stderr, "simulated %d scenarios in %s\n", len(results), time.Since(start).Round(time.Millisecond))

	if *mdOut != "" {
		if err := writeFile(*mdOut, []byte(md.String())); err != nil {
			return err
		}
	}
	if *jsonOut != "" {
		b, err := json.MarshalIndent(results, "", "  ")
		if err != nil {
			return err
		}
		if err := writeFile(*jsonOut, b); err != nil {
			return err
		}
	}
	return nil
}

func writeFile(path string, b []byte) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, b, 0o644)
}
